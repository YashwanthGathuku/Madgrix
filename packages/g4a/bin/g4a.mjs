#!/usr/bin/env node
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { g4aHome, readLog, stats, appendLog, agentMarker } from '../src/lib.mjs';

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BEGIN = '# >>> g4a >>>', END = '# <<< g4a <<<';
const home = g4aHome();
const binDir = path.join(home, 'bin');
const shimPath = path.join(binDir, 'git');

function isShim(f) { try { return fs.readFileSync(f, 'utf8').includes('G4A_SHIM_MARKER'); } catch { return false; } }

// First executable `git` on PATH that is not a g4a shim and not in our bin dir.
export function resolveRealGit(envPath = process.env.PATH || '') {
  for (const d of envPath.split(':').filter(Boolean)) {
    const f = path.join(d, 'git');
    if (path.resolve(d) === path.resolve(binDir)) continue;
    try { fs.accessSync(f, fs.constants.X_OK); } catch { continue; }
    const real = fs.realpathSync(f);
    if (isShim(real)) continue;
    return real;
  }
  return null;
}

const shq = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

function shimScript(real) {
  return `#!/bin/sh
# G4A_SHIM_MARKER - generated by g4a install; remove with g4a uninstall
G4A_REAL_GIT=${shq(real)}
export G4A_REAL_GIT
# Fast path: exec real git untouched unless an agent marker is set and stdout is not a TTY.
if [ -n "$G4A_RAW" ] || [ -n "$G4A_ACTIVE" ] || [ -t 1 ]; then exec "$G4A_REAL_GIT" "$@"; fi
case "\${G4A_AGENT:-}\${CLAUDECODE:-}\${GEMINI_CLI:-}\${G4A_NONTTY_IS_AGENT:-}" in
  "") if ! env | grep -q '^CODEX_'; then exec "$G4A_REAL_GIT" "$@"; fi ;;
esac
[ "\${G4A_AGENT:-}" = "0" ] && exec "$G4A_REAL_GIT" "$@"
exec ${shq(process.execPath)} ${shq(path.join(PKG, 'src', 'shim.mjs'))} "$@"
`;
}

function rcSnippet() { return `${BEGIN}\nexport PATH=${shq(binDir)}:"$PATH"\n${END}\n`; }

function install(args) {
  const rcIdx = args.indexOf('--rc');
  const rc = rcIdx >= 0 ? args[rcIdx + 1] : null;
  const real = resolveRealGit();
  if (!real) { console.error('g4a: no real git found on PATH'); process.exit(1); }
  fs.mkdirSync(binDir, { recursive: true });
  fs.writeFileSync(shimPath, shimScript(real), { mode: 0o755 });
  fs.writeFileSync(path.join(home, 'env.sh'), rcSnippet());
  console.log(`g4a: shim written to ${shimPath} (real git: ${real})`);
  if (rc) {
    const cur = fs.existsSync(rc) ? fs.readFileSync(rc, 'utf8') : '';
    if (!cur.includes(BEGIN)) {
      const addNl = cur.length > 0 && !cur.endsWith('\n');
      fs.writeFileSync(rc, cur + (addNl ? '\n' : '') + rcSnippet());
      fs.writeFileSync(path.join(home, 'rc.json'), JSON.stringify({ rc: path.resolve(rc), addNl }));
    }
    console.log(`g4a: PATH snippet added to ${rc}; open a new shell or: . ${path.join(home, 'env.sh')}`);
  } else {
    console.log(`g4a: to activate, add this to your shell rc (or rerun with --rc ~/.bashrc):\n${rcSnippet()}`);
  }
}

function uninstall(args) {
  const rcIdx = args.indexOf('--rc');
  const rc = rcIdx >= 0 ? args[rcIdx + 1] : null;
  let meta = {};
  try { meta = JSON.parse(fs.readFileSync(path.join(home, 'rc.json'), 'utf8')); } catch {}
  if (rc && fs.existsSync(rc)) {
    const cur = fs.readFileSync(rc, 'utf8');
    const snip = rcSnippet();
    const i = cur.indexOf(snip);
    if (i >= 0) {
      const start = meta.rc === path.resolve(rc) && meta.addNl && i > 0 && cur[i - 1] === '\n' ? i - 1 : i;
      fs.writeFileSync(rc, cur.slice(0, start) + cur.slice(i + snip.length));
    }
  }
  fs.rmSync(path.join(home, 'rc.json'), { force: true });
  for (const f of [shimPath, path.join(home, 'env.sh')]) fs.rmSync(f, { force: true });
  try { fs.rmdirSync(binDir); } catch {}
  console.log('g4a: shim and PATH snippet removed (log.jsonl and tee/ kept; delete ~/.g4a to purge)');
}

function doctor() {
  let ok = true;
  const line = (good, msg) => { console.log(`${good ? 'ok  ' : 'FAIL'} ${msg}`); if (!good) ok = false; };
  line(fs.existsSync(shimPath) && isShim(shimPath), `shim installed at ${shimPath}`);
  const first = (process.env.PATH || '').split(':').map((d) => path.join(d, 'git')).find((f) => { try { fs.accessSync(f, fs.constants.X_OK); return true; } catch { return false; } });
  line(first && path.resolve(first) === path.resolve(shimPath), `first git on PATH is the shim (found: ${first})`);
  const m = fs.existsSync(shimPath) ? fs.readFileSync(shimPath, 'utf8').match(/^G4A_REAL_GIT='(.*)'$/m) : null;
  const real = m?.[1];
  line(real && fs.existsSync(real) && !isShim(real), `real git target: ${real}`);
  if (real && fs.existsSync(real)) {
    const v = execFileSync(real, ['--version'], { encoding: 'utf8', env: { ...process.env, G4A_ACTIVE: '1' } }).trim();
    line(true, v);
  }
  console.log(`info agent marker in this env: ${agentMarker() ?? 'none'}; stdout TTY: ${process.stdout.isTTY ? 'yes' : 'no'}`);
  console.log('info not covered: absolute-path git, git libraries (libgit2/go-git/JGit/isomorphic-git/GitPython object reads), IDE SCM with git.path set to real git, cloud agents');
  process.exitCode = ok ? 0 : 1;
}

function showStats() {
  const { by, tot } = stats(readLog());
  const pct = (b, a) => (b ? (((b - a) / b) * 100).toFixed(1) + '%' : '-');
  console.log('sub        calls compacted   bytesBefore  bytesAfter  saved   (tokens est = ceil(bytes/4))');
  for (const [k, v] of Object.entries(by).sort()) console.log(`${k.padEnd(10)} ${String(v.calls).padStart(5)} ${String(v.compacted).padStart(9)} ${String(v.bytesBefore).padStart(13)} ${String(v.bytesAfter).padStart(11)}  ${pct(v.bytesBefore, v.bytesAfter)}`);
  console.log(`TOTAL      ${String(tot.calls).padStart(5)} ${String(tot.compacted).padStart(9)} ${String(tot.bytesBefore).padStart(13)} ${String(tot.bytesAfter).padStart(11)}  ${pct(tot.bytesBefore, tot.bytesAfter)}`);
  console.log(`est tokens: ${Math.ceil(tot.bytesBefore / 4)} -> ${Math.ceil(tot.bytesAfter / 4)} on compacted calls only`);
}

// One combined dispatcher hook for Claude Code / Codex PreToolUse and Gemini BeforeTool.
// Phase 0: records the event (agent identity + command) and allows; it never rewrites or
// denies, and emits no stdout, so it cannot clash with other hooks (claude-code #79321).
function hook(args) {
  let input = '';
  try { input = fs.readFileSync(0, 'utf8'); } catch {}
  let j = {}; try { j = JSON.parse(input); } catch {}
  const cmd = j?.tool_input?.command ?? j?.tool_input?.cmd ?? null;
  if (typeof cmd === 'string' && /\bgit\b/.test(cmd)) appendLog({ event: 'hook', ts: new Date().toISOString(), agent: args[0] || 'unknown', session: j.session_id ?? null, tool: j.tool_name ?? null, command: cmd });
  process.exit(0);
}

function hooks(args) {
  const which = args[0];
  const cmd = (a) => `${process.execPath} ${path.join(PKG, 'bin', 'g4a.mjs')} hook ${a}`;
  const out = {
    claude: { hooks: { PreToolUse: [{ matcher: 'Bash', hooks: [{ type: 'command', command: cmd('claude') }] }] } },
    codex: { hooks: { PreToolUse: [{ matcher: 'Bash', hooks: [{ type: 'command', command: cmd('codex') }] }] } },
    gemini: { hooks: { BeforeTool: [{ matcher: 'run_shell_command', hooks: [{ type: 'command', command: cmd('gemini') }] }] } },
  };
  if (!out[which]) { console.error('usage: g4a hooks claude|codex|gemini'); process.exit(2); }
  console.log(JSON.stringify(out[which], null, 2));
}

const [cmd, ...rest] = process.argv.slice(2);
({ install, uninstall, doctor, stats: showStats, hook, hooks }[cmd] ?? (() => {
  console.log('usage: g4a install [--rc FILE] | uninstall [--rc FILE] | doctor | stats | hooks claude|codex|gemini | hook <agent>');
  process.exitCode = cmd ? 2 : 0;
}))(rest);
